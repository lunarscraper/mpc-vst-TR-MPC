#!/usr/bin/env python3
"""TR-MPC "full" skin: every slot a module that reskins itself to the drum port its voice comes from.

Writes ports/trkit/layouts/full.conf (+ full_preview.conf: one voice page, full_fx_preview.conf: the FX page, rnd_preview.conf: the
randomise page) and the artwork in ports/trkit/images/. `bash tools/gen_skins_docker.sh gen_trmpc_full.py` runs it where fontTools is
available (the drum ports' lettering is outlined from ../mpc-vst/Assets/fonts); build_ci.sh does that for you.

Everything visual is the drum ports' own: faceplates are cropped from gen_drum_skins.plate_svg, the knobs are the ports' built filmstrips
(copied from _build/<kit>/skin), colours and lettering come from gen_drum_skins.STYLES / text_path.

Each slot has a derived "kit" parameter (sNN_fam: 0 6W6, 1 8W8, 2 CW-78, 3 9W9, 4 the 9W9 kick, which has three extra controls and so a
denser layout); every kit-specific piece of the slot is a `when=sNN_fam:<n>` line. The voice menu doubles as the module title.
"""
